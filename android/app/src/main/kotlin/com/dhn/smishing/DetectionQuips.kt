    @Volatile private var lastIndex: Int = -1

    fun random(): String {
        if (POOL.isEmpty()) return ""
        var idx = (Math.random() * POOL.size).toInt()
        if (POOL.size > 1 && idx == lastIndex) {
            idx = (idx + 1) % POOL.size
        }
        lastIndex = idx
        return POOL[idx]
    }

    fun count(): Int = POOL.size

    init {
        require(POOL.size == 100) { "DetectionQuips POOL size must be 100" }
        require(POOL.all { it.length <= MAX_LEN }) {
            "Each quip must be <= $MAX_LEN chars"
        }
